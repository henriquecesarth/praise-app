// valid case under the production profiles. Deterministic synthetic signals only (no third-party material).
//   npx tsx scripts/m22s3/generate-web-encoder-fixtures.ts
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { Mp3StemStreamValidator, assertConsistentMp3Stems } from '../../src/features/ministry_audio/mp3-stream-validator';
import { MP3_PUBLICATION_VALIDATION } from '../../src/features/ministry_audio/mp3-encoder-profile';
import { createLameWasmBackend } from '../../../web/src/audio/mp3-encoding/mp3-lame-backend';
import { encodeWavStemToMp3 } from '../../../web/src/audio/mp3-encoding/mp3-stem-encoder';

const IDS = ['vocals', 'drums', 'bass', 'guitar', 'piano', 'other'] as const;

function wavOf(rate: number, frames: number, index: number): Uint8Array {
  const out = new Uint8Array(44 + frames * 4);
  const v = new DataView(out.buffer);
  const w = (o: number, s: string) => { for (let i = 0; i < s.length; i++) v.setUint8(o + i, s.charCodeAt(i)); };
  w(0, 'RIFF'); v.setUint32(4, 36 + frames * 4, true); w(8, 'WAVE'); w(12, 'fmt '); v.setUint32(16, 16, true); v.setUint16(20, 1, true);
  v.setUint16(22, 2, true); v.setUint32(24, rate, true); v.setUint32(28, rate * 4, true); v.setUint16(32, 4, true); v.setUint16(34, 16, true);
  w(36, 'data'); v.setUint32(40, frames * 4, true);
  let x = (index + 1) * 2654435761 >>> 0;
  for (let i = 0; i < frames; i++) {
    x = (Math.imul(x, 1664525) + 1013904223) >>> 0;
    const n = (x / 4294967296 - 0.5) * 0.02;
    v.setInt16(44 + i * 4, Math.round((0.3 * Math.sin(i * (0.02 + index * 0.004)) + 0.1 * Math.sin(i * 0.31) + n) * 32767), true);
    v.setInt16(46 + i * 4, Math.round((0.25 * Math.sin(i * (0.017 + index * 0.003)) + 0.1 * Math.sin(i * 0.27) + n) * 32767), true);
  }
  return out;
}

async function encodeSet(rate: 44100 | 48000, frames: number, ids: readonly string[]) {
  const stems = [];
  for (const [index, id] of ids.entries()) {
    const enc = await encodeWavStemToMp3(wavOf(rate, frames, index), { backend: await createLameWasmBackend(), decoderDelayFrames: 529 });
    stems.push({
      manifest: {
        id, codec: 'mp3_cbr256', sampleRate: enc.sampleRate, channels: 2, bitrateKbps: 256, frames: enc.frames, durationSeconds: enc.frames / enc.sampleRate,
        sizeBytes: enc.sizeBytes, sha256: enc.sha256, alignment: enc.alignment,
      },
      base64: Buffer.from(enc.bytes).toString('base64'),
    });
  }
  return stems;
}

async function main() {
  const set44 = await encodeSet(44_100, 26_460, IDS);
  const set48 = await encodeSet(48_000, 28_800, ['vocals']);
  const results = [];
  for (const stem of [...set44, ...set48]) {
    const bytes = Buffer.from(stem.base64, 'base64');
    const validator = new Mp3StemStreamValidator(stem.manifest as never, MP3_PUBLICATION_VALIDATION);
    for (let o = 0; o < bytes.length; o += 4096) validator.write(bytes.subarray(o, o + 4096));
    const r = validator.finish();
    if (r.encoder !== 'LAME3.100') throw new Error(`unexpected encoder ${r.encoder}`);
    results.push(r);
  }
  assertConsistentMp3Stems(results.slice(0, 6));
  const dir = path.resolve(__dirname, '../../../shared/fixtures/ministry-audio-mp3-v2-lame');
  mkdirSync(dir, { recursive: true });
  writeFileSync(path.join(dir, 'web-encoder-cases.json'), JSON.stringify({
    format: 'louvaio.ministry-audio-mp3-web-encoder-cases', version: 1, decoderDelayPolicyFrames: 529,
    note: 'Generated by backend/scripts/m22s3/generate-web-encoder-fixtures.ts with the Web encoder (LAME 3.100 WASM via wasm-media-encoders 0.7.0). Synthetic deterministic signals.',
    sixStems44100: set44, singleStem48000: set48,
  }) + '\n');
  console.log('wrote', set44.length + set48.length, 'stems; sizes', [...set44, ...set48].map((s) => s.manifest.sizeBytes).join(','));
}
main().catch((e) => { console.error(e); process.exit(1); });