// Dev-only generator for src/audio/mp3-calibration-probes.ts (NOT part of the product build).
// Requires a system ffmpeg with libmp3lame; it adds no project dependency.
//   node scripts/generate-mp3-calibration-probes.mjs
// Each probe is a short deterministic stereo signal (low-level noise + isolated full-scale clicks at known
// frames in both channels, including the first and last frames) encoded CBR 256 kbps with an Info/LAME tag.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const FRAMES = 6000;
const DECODER_DELAY = 529; // LAME-decoder delay added to the encoder delay in the contract's encoderDelayFrames
const BR = [0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320];
const SR = [44100, 48000, 32000];
const clicksL = [0, 1500, FRAMES - 1];
const clicksR = [5, 3000, FRAMES - 2];

function signal() {
  const raw = new Float32Array(FRAMES * 2);
  let s = 2024 >>> 0;
  for (let i = 0; i < raw.length; i++) { s = (Math.imul(s, 1664525) + 1013904223) >>> 0; raw[i] = 0.05 * (s / 2147483648 - 1); }
  for (const p of clicksL) raw[2 * p] = 0.95;
  for (const p of clicksR) raw[2 * p + 1] = -0.95;
  return Buffer.from(raw.buffer);
}

function inspect(b) {
  let p = 0, frames = 0, lameDelay = -1;
  while (p + 4 <= b.length && b[p] === 0xff && (b[p + 1] & 0xe0) === 0xe0) {
    const bi = b[p + 2] >> 4, si = (b[p + 2] >> 2) & 3, pad = (b[p + 2] >> 1) & 1;
    if (frames === 0) { const t = b.subarray(p + 36, p + 40).toString(); if (t !== 'Info') throw new Error('missing Info frame'); lameDelay = (b[p + 36 + 120 + 21] << 4) | (b[p + 36 + 120 + 22] >> 4); }
    p += Math.floor(144 * BR[bi] * 1000 / SR[si]) + pad; frames++;
  }
  if (p !== b.length || b.subarray(0, 3).toString() === 'ID3') throw new Error('unexpected trailing bytes or ID3');
  return { mpegAudioFrames: frames - 1, lameDelay };
}

const dir = mkdtempSync(join(tmpdir(), 'mp3probe-'));
writeFileSync(join(dir, 'p.f32'), signal());
const out = {};
for (const sr of [44100, 48000]) {
  const f = join(dir, `p${sr}.mp3`);
  execFileSync('ffmpeg', ['-y', '-v', 'error', '-f', 'f32le', '-ar', String(sr), '-ac', '2', '-i', join(dir, 'p.f32'),
    '-c:a', 'libmp3lame', '-b:a', '256k', '-id3v2_version', '0', '-write_xing', '1', f]);
  const bytes = readFileSync(f);
  const { mpegAudioFrames, lameDelay } = inspect(bytes);
  const encoderDelayFrames = lameDelay + DECODER_DELAY;
  const paddingFrames = mpegAudioFrames * 1152 - encoderDelayFrames - FRAMES;
  out[sr] = { sampleRate: sr, frames: FRAMES, alignment: { encoderDelayFrames, paddingFrames, mpegAudioFrames, infoFrame: true },
    sha256: createHash('sha256').update(bytes).digest('hex'), base64: bytes.toString('base64') };
}
const ts = `// GENERATED by scripts/generate-mp3-calibration-probes.mjs (ffmpeg/libmp3lame). Do not edit by hand.
// Tiny stereo MP3s with isolated full-scale clicks at known frames; used only to observe, on the real
// decoder, whether it trims encoder delay/padding. Click L=+, R=- so channel swaps are detectable.
export interface Mp3CalibrationProbe {
  readonly sampleRate: 44100 | 48000;
  readonly frames: number;
  readonly alignment: { readonly encoderDelayFrames: number; readonly paddingFrames: number; readonly mpegAudioFrames: number };
  readonly sha256: string;
  readonly base64: string;
}
export const MP3_PROBE_CLICKS_L = ${JSON.stringify(clicksL)} as const;
export const MP3_PROBE_CLICKS_R = ${JSON.stringify(clicksR)} as const;
export const MP3_CALIBRATION_PROBES: Readonly<Record<44100 | 48000, Mp3CalibrationProbe>> = {
${[44100, 48000].map((sr) => `  ${sr}: {
    sampleRate: ${sr}, frames: ${FRAMES},
    alignment: ${JSON.stringify({ encoderDelayFrames: out[sr].alignment.encoderDelayFrames, paddingFrames: out[sr].alignment.paddingFrames, mpegAudioFrames: out[sr].alignment.mpegAudioFrames })},
    sha256: '${out[sr].sha256}',
    base64: '${out[sr].base64}',
  },`).join('\n')}
};
`;
writeFileSync(new URL('../src/audio/mp3-calibration-probes.ts', import.meta.url), ts);
console.log(JSON.stringify(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, { ...v, base64: v.base64.length }]))));
